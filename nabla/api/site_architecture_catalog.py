"""Authenticated sanitized Backstage v2 read model for the Site Alban server.

Never turn the legacy services.json contract into a second catalog authority.
The published v2 source is generated by nabla-compose from Backstage descriptors.
"""

from __future__ import annotations

import asyncio
import hashlib
import json
import logging
import os
import re
from secrets import compare_digest
import time
from typing import Any, Literal
from urllib.parse import urlsplit

import httpx
from pydantic import BaseModel, ConfigDict, Field, ValidationError

logger = logging.getLogger(__name__)

_SOURCE_URL = os.getenv(
    "HOMELAB_CATALOG_V2_URL",
    "https://raw.githubusercontent.com/AlbanAndrieu/nabla-compose/master/catalog/generated/entities.json",
).strip()
_MAX_BYTES = 2_000_000
_TIMEOUT_SECONDS = 5.0
_CACHE_TTL_SECONDS = 300.0
_REF_RE = re.compile(r"^(?:api|component|domain|group|resource|system):[a-z0-9-]+/[a-z0-9]+(?:-[a-z0-9]+)*$")
_NAME_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
_TAG_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,63}$")
_SOURCE_PATH_RE = re.compile(r"^(?:apps/[a-z0-9_-]+|catalog)/catalog-info\.yaml$")
_REVISION_RE = re.compile(r"^sha256:[0-9a-f]{64}$")
_UNSAFE_LABEL_RE = re.compile(r"https?://|(?:\d{1,3}\.){3}\d{1,3}|\.int\.|[:/\\@]", re.I)
_KINDS = frozenset(("API", "Component", "Domain", "Group", "Resource", "System"))
_CRITICALITY_LABELS = (
    "albandrieu.com/operational-criticality",
    "albandrieu.com/business-criticality",
)
_SPEC_SCALARS = ("type", "lifecycle")
_SPEC_REFS = ("owner", "system", "domain", "subcomponentOf")
_SPEC_RELATIONS = ("dependsOn", "consumesApis", "providesApis", "children")


class SiteCatalogV2Unavailable(RuntimeError):
    """No valid, fresh authoritative Backstage v2 source is available."""


class SiteV2Metadata(BaseModel):
    """Explicit allowlist: do not propagate BIA annotations, host or URL data."""

    model_config = ConfigDict(extra="forbid", frozen=True, strict=True)
    name: str = Field(min_length=1, max_length=128)
    namespace: str | None = None
    title: str | None = None
    tags: list[str] | None = None
    labels: dict[str, str] | None = None


class SiteV2Entity(BaseModel):
    """Entity identity, portable provenance and reviewed dependency edges only."""

    model_config = ConfigDict(extra="forbid", frozen=True, strict=True)
    apiVersion: Literal["backstage.io/v1alpha1"] = "backstage.io/v1alpha1"
    kind: Literal["API", "Component", "Domain", "Group", "Resource", "System"]
    entityRef: str = Field(pattern=r"^(api|component|domain|group|resource|system):[a-z0-9-]+/[a-z0-9-]+$")
    sourcePath: str
    metadata: SiteV2Metadata
    spec: dict[str, str | list[str]]


class SiteArchitectureCatalogV2(BaseModel):
    """Matching the existing nabla-site-alban HomelabCatalogV2 wire contract."""

    model_config = ConfigDict(extra="forbid", frozen=True, strict=True)
    schemaVersion: Literal[2] = 2
    model: Literal["backstage"] = "backstage"
    catalogRevision: str = Field(pattern=r"^sha256:[0-9a-f]{64}$")
    entities: list[SiteV2Entity] = Field(min_length=1, max_length=2000)


_cache: tuple[float, SiteArchitectureCatalogV2] | None = None
_refresh_lock = asyncio.Lock()


def _validated_source_url(url: str) -> str:
    """Do not permit catalog URL configuration to become a generic SSRF proxy."""
    parsed = urlsplit(url)
    prefix = "/AlbanAndrieu/nabla-compose/"
    suffix = "/catalog/generated/entities.json"
    if (
        parsed.scheme != "https"
        or parsed.netloc != "raw.githubusercontent.com"
        or not parsed.path.startswith(prefix)
        or not parsed.path.endswith(suffix)
        or parsed.query
        or parsed.fragment
    ):
        raise ValueError("v2 catalog source must be the approved Nabla GitHub artifact")
    ref = parsed.path[len(prefix) : -len(suffix)]
    if not ref or any(
        part in ("", ".", "..") or not re.fullmatch(r"[A-Za-z0-9_.-]+", part)
        for part in ref.split("/")
    ):
        raise ValueError("v2 catalog revision must be a valid Git ref")
    return url


def _clean_display_title(raw: Any) -> str | None:
    if raw is None:
        return None
    if not isinstance(raw, str) or not raw.strip() or len(raw) > 128 or _UNSAFE_LABEL_RE.search(raw):
        raise ValueError("unsafe Backstage display title")
    return raw


def _valid_ref(raw: Any, refs: set[str]) -> str:
    if not isinstance(raw, str) or not _REF_RE.fullmatch(raw) or raw not in refs:
        raise ValueError("unresolved Backstage entity relationship")
    return raw


def project_site_catalog_v2(raw: object) -> SiteArchitectureCatalogV2:
    """Validate source revision then only copy reviewed fields into a v2 DTO.

    catalogRevision is the digest of the FULL source graph, not the redacted
    representation; clients use it as an origin version ID, not as a DTO checksum.
    """
    if not isinstance(raw, dict) or raw.get("schemaVersion") != 2 or raw.get("model") != "backstage":
        raise ValueError("unsupported Backstage catalog schema")
    values = raw.get("entities")
    if (
        not isinstance(values, list)
        or not 0 < len(values) <= 2000
        or not all(isinstance(v, dict) for v in values)
    ):
        raise ValueError("invalid Backstage entities")
    revision = raw.get("catalogRevision")
    if not isinstance(revision, str) or not _REVISION_RE.fullmatch(revision):
        raise ValueError("invalid canonical revision")
    ordered = sorted(values, key=lambda entity: str(entity.get("entityRef") or ""))
    digest = hashlib.sha256(
        json.dumps(ordered, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")
    ).hexdigest()
    if not compare_digest(revision, "sha256:" + digest):
        raise ValueError("Backstage source revision mismatch")
    refs = {entity.get("entityRef") for entity in values}
    if len(refs) != len(values) or not all(
        isinstance(ref, str) and _REF_RE.fullmatch(ref) for ref in refs
    ):
        raise ValueError("ambiguous Backstage entity refs")

    output: list[SiteV2Entity] = []
    for entity in ordered:
        metadata = entity.get("metadata")
        source_spec = entity.get("spec")
        kind = entity.get("kind")
        source_path = entity.get("sourcePath")
        if (
            entity.get("apiVersion") != "backstage.io/v1alpha1"
            or kind not in _KINDS
            or not isinstance(metadata, dict)
            or not isinstance(source_spec, dict)
            or not isinstance(source_path, str)
            or not _SOURCE_PATH_RE.fullmatch(source_path)
        ):
            raise ValueError("invalid Backstage entity")
        name = metadata.get("name")
        namespace = metadata.get("namespace", "default")
        if (
            not isinstance(name, str)
            or not _NAME_RE.fullmatch(name)
            or not isinstance(namespace, str)
            or not _NAME_RE.fullmatch(namespace)
            or entity["entityRef"] != f"{kind.lower()}:{namespace}/{name}"
        ):
            raise ValueError("inconsistent Backstage identity")
        title = _clean_display_title(metadata.get("title"))
        raw_tags = metadata.get("tags", [])
        if not isinstance(raw_tags, list) or not all(isinstance(tag, str) for tag in raw_tags):
            raise ValueError("invalid Backstage tags")
        tags = [tag for tag in raw_tags if _TAG_RE.fullmatch(tag)][:24]
        raw_labels = metadata.get("labels") or {}
        if not isinstance(raw_labels, dict):
            raise ValueError("invalid Backstage labels")
        labels = {
            key: raw_labels[key]
            for key in _CRITICALITY_LABELS
            if raw_labels.get(key) in ("critical", "high", "medium", "low")
        }
        clean_metadata = SiteV2Metadata(
            name=name,
            namespace=namespace if namespace != "default" else None,
            title=title,
            tags=tags or None,
            labels=labels or None,
        )
        spec: dict[str, str | list[str]] = {}
        for key in _SPEC_SCALARS:
            field = source_spec.get(key)
            if isinstance(field, str) and _TAG_RE.fullmatch(field):
                spec[key] = field
        for key in _SPEC_REFS:
            value = source_spec.get(key)
            if value is not None:
                spec[key] = _valid_ref(value, refs)
        for key in _SPEC_RELATIONS:
            targets = source_spec.get(key)
            if targets is not None:
                if not isinstance(targets, list):
                    raise ValueError("invalid Backstage relations")
                spec[key] = [_valid_ref(target, refs) for target in targets]
        output.append(
            SiteV2Entity(
                kind=kind,
                entityRef=entity["entityRef"],
                sourcePath=source_path,
                metadata=clean_metadata,
                spec=spec,
            )
        )
    return SiteArchitectureCatalogV2(catalogRevision=revision, entities=output)


async def _download_site_catalog_v2() -> SiteArchitectureCatalogV2:
    url = _validated_source_url(_SOURCE_URL)
    async with httpx.AsyncClient(
        timeout=httpx.Timeout(_TIMEOUT_SECONDS),
        follow_redirects=False,
        trust_env=False,
        headers={"Accept": "application/json", "User-Agent": "fastapi-sample-site-catalog-v2/1"},
    ) as client:
        response = await client.get(url)
        response.raise_for_status()
        if len(response.content) > _MAX_BYTES:
            raise ValueError("authoritative catalog exceeds size budget")
        return project_site_catalog_v2(response.json())


async def fetch_site_catalog_v2() -> SiteArchitectureCatalogV2:
    """Singleflight read: 5-minute cache of verified v2 only; never fall back."""
    global _cache
    now = time.monotonic()
    if _cache is not None and now < _cache[0]:
        return _cache[1]
    async with _refresh_lock:
        now = time.monotonic()
        if _cache is not None and now < _cache[0]:
            return _cache[1]
        try:
            result = await _download_site_catalog_v2()
        except (httpx.HTTPError, ValueError, TypeError, ValidationError, json.JSONDecodeError) as exc:
            logger.warning("Site Backstage v2 unavailable exception_type=%s", type(exc).__name__)
            raise SiteCatalogV2Unavailable("Authoritative Backstage v2 catalog unavailable") from None
        _cache = (time.monotonic() + _CACHE_TTL_SECONDS, result)
        return result


def reset_site_catalog_v2_cache() -> None:
    """Explicit cache reset for isolated tests, never a public endpoint."""
    global _cache
    _cache = None
