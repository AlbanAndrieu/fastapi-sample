"""Desired exposure routes read from the Backstage v2 catalog (``x-nabla.exposure``).

FastAPI is a read model, not a second inventory: each route is identified by
its full entity ref plus its route name, and only projects intent generated by
nabla-compose. Observations (probes, Cloudflare, TrueNAS) stay separate.
"""

from __future__ import annotations

import logging
import time
from collections.abc import Mapping, Sequence
from ipaddress import ip_address
from typing import Annotated, Any, Literal
from urllib.parse import urlsplit

from pydantic import BaseModel, ConfigDict, Field, ValidationError, model_validator

from nabla.api.site_architecture_catalog import (
    SiteCatalogV2Unavailable,
    fetch_catalog_v2_source,
    load_catalog_snapshot,
)

_log = logging.getLogger(__name__)

CLOUDFLARE_TUNNEL_GATEWAY = "resource:default/cloudflare-tunnel"
DIRECT_WAN_GATEWAY = "resource:default/pfsense-haproxy"
_PFSENSE_REF = "resource:default/pfsense"
_DIRECT_EXTERNAL_SUFFIX = ".int.albandrieu.com"
_SLUG = r"^[a-z0-9]+(?:-[a-z0-9]+)*$"
_HOSTNAME = r"^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?)+$"
_FAILURE_RETRY_SECONDS = 60.0


class CatalogRoute(BaseModel):
    """One desired route of one Backstage entity; never a runtime observation."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    entity_ref: str = Field(pattern=r"^(?:api|component|domain|group|resource|system):[a-z0-9-]+/[a-z0-9]+(?:-[a-z0-9]+)*$")
    route: str = Field(default="default", pattern=_SLUG)
    # Health-board row id: entity name, plus ``-<route>`` beyond its first route.
    service_id: str = Field(pattern=_SLUG, max_length=128)
    name: str = Field(min_length=1, max_length=160)
    description: str | None = None
    visibility: Literal["public", "lan", "cluster", "host"] = "lan"
    protocol: Literal["HTTPS", "HTTP", "TCP"] = "HTTPS"
    hostnames: tuple[Annotated[str, Field(pattern=_HOSTNAME)], ...] = ()
    port: int | None = Field(default=None, ge=1, le=65535)
    gateway_ref: str | None = None
    access_required: bool = False
    probe_path: str | None = None
    risk_reason: str | None = None
    backend_host: str | None = None
    backend_port: int | None = Field(default=None, ge=1, le=65535)
    backend_tls: bool = False
    probe_rank: int | None = Field(default=None, ge=0, le=1000, strict=True)
    probe_position: int = Field(default=0, ge=0, strict=True)

    @property
    def public(self) -> bool:
        """Desired visibility, never proof that the route is reachable."""
        return self.visibility == "public"

    @property
    def url(self) -> str | None:
        """Desired HTTPS endpoint of the route's first hostname."""
        if not self.hostnames:
            return None
        return f"https://{self.hostnames[0]}" + (f":{self.port}" if self.port else "")

    @property
    def cloudflare_edge(self) -> bool | None:
        """Cloudflare Tunnel/Access edge (True), direct WAN ingress (False), else None."""
        return {CLOUDFLARE_TUNNEL_GATEWAY: True, DIRECT_WAN_GATEWAY: False}.get(self.gateway_ref or "")

    @property
    def public_https_probe_url(self) -> str | None:
        """Outside-in probe target, only for an intentionally public route."""
        if not self.public or self.url is None:
            return None
        return self.url + (self.probe_path or "/")

    @model_validator(mode="after")
    def validate_route(self) -> CatalogRoute:
        """Fail closed on malformed probe paths and implausible public endpoints."""
        if self.probe_path is not None:
            parsed = urlsplit(self.probe_path)
            if not self.probe_path.startswith("/") or self.probe_path.startswith("//") or parsed.scheme or parsed.netloc:
                raise ValueError("probePath must be a relative URL path")
        if not self.public:
            return self
        if not self.hostnames:
            raise ValueError("a public route requires a hostname")
        host = self.hostnames[0]
        if host.endswith((".local", ".localdomain")):
            raise ValueError("a public route must not target a local hostname")
        try:
            address = ip_address(host)
        except ValueError:
            address = None
        if address is not None and not address.is_global:
            raise ValueError("a public route must not target a non-global IP address")
        if host.endswith(_DIRECT_EXTERNAL_SUFFIX) and self.cloudflare_edge is True and not self.access_required:
            raise ValueError("a Cloudflare *.int.albandrieu.com route cannot disable Cloudflare Access")
        return self


def routes_from_catalog(raw: Mapping[str, Any]) -> tuple[CatalogRoute, ...]:
    """Project every ``x-nabla.exposure`` route of a revision-verified entities.json."""
    routes: list[CatalogRoute] = []
    for entity in raw.get("entities") or ():
        spec = entity.get("x-nabla") or {}
        exposure = spec.get("exposure") or []
        if not exposure:
            continue
        ref = entity["entityRef"]
        metadata = entity.get("metadata") or {}
        entity_name = ref.split("/", 1)[1]
        title = metadata.get("title") or metadata.get("name")
        policy = spec.get("probePolicy") or {}
        if len({item.get("name") for item in exposure}) != len(exposure):
            raise ValueError(f"duplicate route names on {ref}")
        for index, item in enumerate(exposure):
            backend = item.get("backend") or {}
            routes.append(
                CatalogRoute(
                    entity_ref=ref,
                    route=item.get("name"),
                    service_id=entity_name if index == 0 else f"{entity_name}-{item.get('name')}",
                    name=title if len(exposure) == 1 else f"{title} ({item.get('name')})",
                    description=metadata.get("description"),
                    visibility=item.get("visibility"),
                    protocol=item.get("protocol"),
                    hostnames=tuple(item.get("hostnames") or ()),
                    port=item.get("port"),
                    gateway_ref=item.get("gatewayRef"),
                    access_required=(item.get("access") or {}).get("required") is True,
                    probe_path=item.get("probePath"),
                    risk_reason=(item.get("riskAcceptance") or {}).get("reason"),
                    backend_host=backend.get("host"),
                    backend_port=backend.get("port"),
                    backend_tls=backend.get("appProtocol") == "https",
                    probe_rank=policy.get("rank"),
                    probe_position=policy.get("position") or 0,
                ),
            )
    service_ids = [route.service_id for route in routes]
    if len(set(service_ids)) != len(service_ids):
        raise ValueError("ambiguous health-board service ids across entity kinds")
    return tuple(routes)


_state: dict[str, Any] = {"revision": None, "routes": (), "retry_at": 0.0}


def clear_catalog_routes_cache() -> None:
    """Reset the route projection cache; intended for tests and explicit refreshes."""
    _state.update(revision=None, routes=(), retry_at=0.0)


def _snapshot_routes() -> tuple[str | None, tuple[CatalogRoute, ...]]:
    try:
        snapshot = load_catalog_snapshot()
        return snapshot["catalogRevision"], routes_from_catalog(snapshot)
    except (OSError, ValueError, KeyError, TypeError) as exc:
        _log.error("Packaged Backstage v2 snapshot is unusable: %s", exc)
        return None, ()


async def fetch_catalog_routes() -> list[CatalogRoute]:
    """Return verified v2 route intent, else last-known-good, else the packaged snapshot."""
    now = time.monotonic()
    if now < _state["retry_at"]:
        return list(_state["routes"])
    try:
        raw = await fetch_catalog_v2_source()
        if raw["catalogRevision"] != _state["revision"]:
            routes = routes_from_catalog(raw)
            # A pre-cutover catalog has no exposure intent; an empty inventory would turn /sickz green blind.
            if not routes:
                raise ValueError("Backstage v2 catalog carries no x-nabla.exposure route")
            _state.update(routes=routes, revision=raw["catalogRevision"])
    except (SiteCatalogV2Unavailable, ValidationError, ValueError, KeyError, TypeError) as exc:
        if not _state["routes"]:
            revision, routes = _snapshot_routes()
            _state.update(revision=revision, routes=routes)
        _state["retry_at"] = now + _FAILURE_RETRY_SECONDS
        _log.warning("Backstage v2 route intent unavailable; using cached or packaged routes: %s", type(exc).__name__)
    return list(_state["routes"])


def _https_key(url: str) -> str:
    return url.rstrip("/") + "/"


def sickz_targets(
    routes: Sequence[CatalogRoute],
) -> tuple[list[list[str]], dict[str, str], dict[str, dict[str, Any]]]:
    """Every routed hostname is a /sickz exposure target, private ones included.

    The pfSense administration routes are checked by the dedicated port-policy
    row and are therefore not duplicated here.
    """
    groups: list[list[str]] = []
    names: dict[str, str] = {}
    expectations: dict[str, dict[str, Any]] = {}
    for route in routes:
        if route.entity_ref == _PFSENSE_REF or route.url is None:
            continue
        key = _https_key(route.url)
        groups.append([key])
        names[key] = route.name
        expectations[key] = {
            "external": route.public,
            "tunnel_secure": route.cloudflare_edge,
            "expected_reachable": route.public,
        }
    return groups, names, expectations


async def sickz_catalog() -> tuple[list[list[str]], dict[str, str], dict[str, dict[str, Any]]]:
    """Return /sickz targets plus row names and reachability intent."""
    return sickz_targets(await fetch_catalog_routes())
